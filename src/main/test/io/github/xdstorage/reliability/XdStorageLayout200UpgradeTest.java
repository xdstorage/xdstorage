    private static void move(final File source, final File target) throws IOException {
        Files.createDirectories(target.toPath().getParent());
        Files.move(source.toPath(), target.toPath(), StandardCopyOption.ATOMIC_MOVE);
    }

    private static int countFiles(final File root) throws IOException {
        try (final Stream<Path> walk = Files.walk(root.toPath())) {
            return (int) walk.filter(Files::isRegularFile).count();
        }
    }
