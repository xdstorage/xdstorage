    @Test
    @DisplayName("crash-матрица: сбой ПОСЛЕ переноса инфра-деревьев → следующее открытие доделывает базы")
    public void crashMatrix_InfraMovedBasesNot_CompletesOnNextOpen() throws Exception {
        // simulate the crash: the infra moved, the index bases still at the legacy location
        move(new File(FIXTURE_ROOT + "/data/XdStorageBTree"), new File(FIXTURE_ROOT + "/indexes/XdStorageBTree"));
        move(new File(FIXTURE_ROOT + "/data/XdStorageBTreeNode"), new File(FIXTURE_ROOT +
                "/indexes/XdStorageBTreeNode"));
        // the marker still v2 (the crash happened before the marker rewrite)
        assertEquals("2", readMarker().getProperty("formatVersion"), "полумигрированное состояние: маркер ещё v2");

        final IXdFileStorage storage = XdStorageProvider.newOrGetFileStorage("layout-mig-crash1", FIXTURE_ROOT, 64);
        try {
            assertTrue(new File(FIXTURE_ROOT + "/indexes/Gal200Child/index.yaml").isFile(),
                    "следующее открытие доделало перенос id-index баз");
            assertTrue(new File(FIXTURE_ROOT + "/indexes/Gal200Hash/index.yaml").isFile(), "хэш-база доделана");
            assertFalse(new File(FIXTURE_ROOT + "/data/Gal200Child/index.yaml").exists(), "легаси-базы исчезли");
            assertEquals("3", readMarker().getProperty("formatVersion"), "маркер доведён до v3");
            final IXdStorageTransaction tx = storage.beginTransaction();
            assertEquals("Планета-2-1", storage.load(Gal200Child.class, "gal-2-c1", tx).getLabel(),
                    "данные живы после доделки миграции");
            tx.commit();
        } finally {
            storage.shutdown();
        }
    }

    @Test
    @DisplayName("crash-матрица: сбой ПОСЛЕ одного класса → второй класс доделывается, данные обоих целы")
    public void crashMatrix_OneClassMovedOtherNot_CompletesOnNextOpen() throws Exception {
        // simulate: only Gal200Child's base migrated (the crash hit before Gal200Hash)
        move(new File(FIXTURE_ROOT + "/data/Gal200Child/index.yaml"),
                new File(FIXTURE_ROOT + "/indexes/Gal200Child/index.yaml"));

        final IXdFileStorage storage = XdStorageProvider.newOrGetFileStorage("layout-mig-crash2", FIXTURE_ROOT, 64);
        try {
            assertTrue(new File(FIXTURE_ROOT + "/indexes/Gal200Hash/index.yaml").isFile(), "второй класс доделан");
            final IXdStorageTransaction tx = storage.beginTransaction();
            assertNotNull(storage.load(Gal200Child.class, "gal-1-c0", tx), "класс 1 жив");
            assertNotNull(storage.load(Gal200Hash.class, "hash-4", tx), "класс 2 жив");
            assertNotNull(storage.load(Gal200Parent.class, "gal-1", tx), "родители живы");
            tx.commit();
        } finally {
            storage.shutdown();
        }
    }

    // ────────────────────────────────────────────────────────────────────────
    // 3. Idempotency
    // ────────────────────────────────────────────────────────────────────────

    @Test
    @DisplayName("идемпотентность: третье открытие после полной миграции — ноль перемещений, маркер v3 стабилен")
    public void idempotent_SecondAndThirdOpen_NoMoves() throws Exception {
        final IXdFileStorage first = XdStorageProvider.newOrGetFileStorage("layout-mig-idem", FIXTURE_ROOT, 64);
        first.shutdown();
        final int fileCountAfterFirst = countFiles(new File(FIXTURE_ROOT));
        final Properties afterFirst = readMarker();
        assertEquals("3", afterFirst.getProperty("formatVersion"), "после первой миграции маркер v3");

        // two more opens: nothing moves, the marker stays
        final IXdFileStorage second = XdStorageProvider.newOrGetFileStorage("layout-mig-idem", FIXTURE_ROOT, 64);
        second.shutdown();
        final IXdFileStorage third = XdStorageProvider.newOrGetFileStorage("layout-mig-idem", FIXTURE_ROOT, 64);
        try {
            final IXdStorageTransaction tx = third.beginTransaction();
            assertNotNull(third.load(Gal200Child.class, "gal-0-c1", tx), "контент цел после трёх открытий");
            tx.commit();
        } finally {
            third.shutdown();
        }
        assertEquals(fileCountAfterFirst, countFiles(new File(FIXTURE_ROOT)),
                "ни один файл не появился/не исчез при повторных открытиях");
        assertEquals("3", readMarker().getProperty("formatVersion"), "маркер стабилен на v3");
    }

    // ────────────────────────────────────────────────────────────────────────
    // 4. The downgrade refusal (the v3 stamp makes the CHANGELOG claim true)
    // ────────────────────────────────────────────────────────────────────────

    @Test
    @DisplayName("downgrade-отказ: папка с formatVersion выше поддерживаемой открывается ГРОМКИМ отказом")
    public void downgrade_NewerFormatVersion_RefusesLoudly() throws Exception {
        final IXdFileStorage storage = XdStorageProvider.newOrGetFileStorage("layout-mig-dg", FIXTURE_ROOT, 64);
        try {
            final IXdStorageTransaction tx = storage.beginTransaction();
            final Gal200Hash saved = new Gal200Hash();
            saved.setId("dg-1");
            saved.setValue("x");
            storage.save(saved, tx);
            tx.commit();
        } finally {
            storage.shutdown();
        }
        // simulate a future version's stamp
        final Properties meta = readMarker();
        meta.setProperty("formatVersion", "99");
        try (final OutputStream out = Files.newOutputStream(new File(FIXTURE_ROOT + "/.xdstorage.meta").toPath())) {
            meta.store(out, "simulated future stamp");
        }
        final XdStorageRuntimeException refused = assertThrows(XdStorageRuntimeException.class,
                () -> XdStorageProvider.newOrGetFileStorage("layout-mig-dg-2", FIXTURE_ROOT, 64),
                "папка от «будущей» версии обязана отказать громко (2.0.0 делает то же с v3-маркером)");
        assertTrue(refused.getMessage().contains("format v99"), "сообщение содержит поколение: " + refused
                .getMessage());
    }

    // ────────────────────────────────────────────────────────────────────────
    // The helpers
